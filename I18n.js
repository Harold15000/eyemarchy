// "auto" follows the shell's locale (LANG); anything unknown is English.
function resolve(setting, localeName, langEnv) {
  if (LANGUAGES.indexOf(setting) >= 0) return setting
  var candidates = [String(langEnv || ""), String(localeName || "")]
  for (var i = 0; i < candidates.length; i++) {
    var code = candidates[i].split(/[_.@-]/)[0].toLowerCase()
    if (LANGUAGES.indexOf(code) >= 0) return code
  }
  return "en"
}

function tr(lang, key, a, b) {
  var table = STRINGS[lang] || STRINGS.en
  var s = table[key]
  if (s === undefined) s = STRINGS.en[key]
  if (s === undefined) return key
  if (a !== undefined) s = s.replace("%1", a)
  if (b !== undefined) s = s.replace("%2", b)
  return s
}
